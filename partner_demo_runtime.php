function pda_rewrite(string $text):string {
    // Preserve route basenames so the existing popup/print handlers keep working.
    $text=str_replace('지도 키 설정을 확인해 주세요. 저장된 좌표와 정보는 유지됩니다.','체험에서는 미리 입력된 예시 위치를 사용합니다. 실제 건물 연결 후 지도에서 위치를 지정할 수 있어요.',$text);
    return preg_replace_callback('~(?<=[\x22\x27`(=])/([A-Za-z0-9_-]+\.(?:php|js|css))(?=[?\x22\x27`\s)#])~',static fn($m)=>PDA_PREFIX.$m[1],$text);
}
function pda_store(string $dir,string $name,array $data,bool $guard=false):void {
    $file=$dir.'/'.$name;if(!is_dir(dirname($file)))mkdir(dirname($file),0700,true);
    file_put_contents($file,($guard?"<?php exit; ?>\n":'').json_encode($data,JSON_UNESCAPED_UNICODE|JSON_PRETTY_PRINT|JSON_THROW_ON_ERROR),LOCK_EX);
}
/** Remove only expired directories generated by this demo, at most twice per hour. */
function pda_cleanup(string $base,string $active):void {
    $stamp=$base.'/.cleanup';
    if(is_file($stamp)&&filemtime($stamp)>time()-3600)return;
    $lock=fopen($stamp,'c+');if(!$lock||!flock($lock,LOCK_EX|LOCK_NB)){if($lock)fclose($lock);return;}
    try {
        touch($stamp);$removed=0;
        foreach(new DirectoryIterator($base) as $entry){
            if($removed>=2)break;
            if($entry->isDot()||$entry->isLink()||!$entry->isDir()||!preg_match('/^[a-f0-9]{64}$/D',$entry->getFilename())||$entry->getFilename()===$active||$entry->getMTime()>time()-172800)continue;
            $walk=new RecursiveIteratorIterator(new RecursiveDirectoryIterator($entry->getPathname(),FilesystemIterator::SKIP_DOTS),RecursiveIteratorIterator::CHILD_FIRST);
            foreach($walk as $file){if($file->isDir()&&!$file->isLink())rmdir($file->getPathname());else unlink($file->getPathname());}
            rmdir($entry->getPathname());$removed++;
        }
    }finally{flock($lock,LOCK_UN);fclose($lock);}
}
function pda_private_dir(string $dir):void {
    if(is_link($dir))throw new RuntimeException('Demo storage must not be a symbolic link: '.$dir);
    if(!is_dir($dir)&&!@mkdir($dir,0700)&&!is_dir($dir))throw new RuntimeException('Cannot create demo storage directory: '.$dir);
    if(!is_writable($dir))throw new RuntimeException('Demo storage directory is not writable: '.$dir);
}
function pda_runtime(string $scope,array $manifest):string {
    if(!preg_match('/^[a-f0-9]{64}$/D',$scope))throw new RuntimeException('Invalid demo storage scope.');
    // FPM may forbid the OS default (/var/tmp) while allowing its configured
    // upload temp directory. Use the server's permitted temp root when supplied.
    $configured=trim((string)ini_get('upload_tmp_dir'));
    $temp=realpath($configured!==''?$configured:sys_get_temp_dir());
    if($temp===false||!is_dir($temp)||!is_writable($temp))throw new RuntimeException('Demo temporary root is unavailable.');
    $base=$temp.'/sobang-partner-demo-'.substr(hash('sha256',__DIR__),0,20);
    pda_private_dir($base);
    pda_cleanup($base,$scope);
    $dir=$base.'/'.$scope;
    pda_private_dir($dir);
    $lock=fopen($dir.'/.source.lock','c+');if(!$lock||!flock($lock,LOCK_EX))throw new RuntimeException('체험 준비 중입니다. 다시 열어 주세요.');
    try {
        $cached=json_decode((string)@file_get_contents($dir.'/.sources.json'),true)?:[];$fingerprints=[];
        foreach($manifest['sources'] as $name){
            if(!preg_match('/^[A-Za-z0-9_-]+\.php$/D',$name))throw new RuntimeException('체험 파일 구성을 확인해 주세요.');
            $src=__DIR__.'/'.$name;$dest=$dir.'/'.$name;
            if(!is_file($src)||is_link($src))throw new RuntimeException('체험에 필요한 파일이 없습니다.');
            $fingerprints[$name]='adapter3:'.hash_file('sha256',$src);
            if(!is_file($dest)||($cached[$name]??'')!==$fingerprints[$name]){
                $source=(string)file_get_contents($src);
                // The gateway owns the cookie-less demo session. Legacy pages may
                // configure cookies and start it unconditionally; adapt those calls only.
                $source=preg_replace('~session_set_cookie_params\(\[[^;]*\]\)\s*;~',';',$source);
                $source=preg_replace('~ini_set\([\x22\x27]session\.cookie_httponly[\x22\x27]\s*,[^;]*\)\s*;~',';',$source);
                $source=preg_replace('~(?<![A-Za-z0-9_])session_start\(\);~','if(session_status()!==PHP_SESSION_ACTIVE)session_start();',$source);
                $tmp=$dest.'.tmp';file_put_contents($tmp,$source,LOCK_EX);chmod($tmp,0600);rename($tmp,$dest);
            }
        }
        file_put_contents($dir.'/.sources.json',json_encode($fingerprints),LOCK_EX);
        $stubs=[
            'manager_edit_guard.php'=>"<?php if(session_status()!==PHP_SESSION_ACTIVE)session_start(); if(!defined('MANAGER_FULL_DASHBOARD'))define('MANAGER_FULL_DASHBOARD',true);",
            '_imp.php'=>"<?php /* Isolated example: no production impersonation. */",
            'api_keys.php'=>"<?php return [];",
            'telegram_config.php'=>"<?php function send_telegram(string \$text):bool{return false;}",
            'mail_config.php'=>"<?php return [];",
            'building_registry_http.php'=>"<?php function br_http_get(string \$url,array \$headers=[],?callable \$transport=null):array{return ['ok'=>false,'retryable'=>false,'error'=>'체험에서는 준비된 예시 건물정보를 이용해 주세요.'];} function br_response_state(array \$r):array{return \$r;}"
        ];
        foreach($stubs as $name=>$source)if(!is_file($dir.'/'.$name)||file_get_contents($dir.'/'.$name)!==$source)file_put_contents($dir.'/'.$name,$source,LOCK_EX);
        foreach(['data','sessions'] as $name)pda_private_dir($dir.'/'.$name);
    } finally {flock($lock,LOCK_UN);fclose($lock);}
    return $dir;
}
